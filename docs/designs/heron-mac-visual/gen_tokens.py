"""Generate tokens.css from tokens.json and check WCAG contrast. Run: python3 -I gen_tokens.py"""
import json, sys, pathlib
here = pathlib.Path(__file__).parent
t = json.loads((here / "tokens.json").read_text())

def lum(h):
    c = [int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def ratio(a, b):
    a, b = lum(a), lum(b)
    return (max(a, b) + 0.05) / (min(a, b) + 0.05)

fails = []
for th, modes in t["themes"].items():
    for m, v in modes.items():
        s = t["status"][m]
        for bg in ("window", "sidebar", "surface", "raised"):
            for fg, need in (("ink", 7), ("ink2", 4.5), ("ink3", 4.5)):
                if ratio(v[fg], v[bg]) < need: fails.append(f"{th}/{m} {fg} on {bg}")
        for k in ("waiting", "outside", "danger", "ok"):
            for bg in (s[k + "Soft"], v["surface"]):
                if ratio(s[k], bg) < 4.5: fails.append(f"{th}/{m} {k} on {bg}")
        for a, av in t["accents"].items():
            on = av["onLight" if m == "light" else "onDark"]
            for fg, bg in ((av[m], v["surface"]), (on, av[m]), (av[m], av[m + "Soft"])):
                if ratio(fg, bg) < 4.5: fails.append(f"{th}/{m} accent {a} {fg} on {bg}")
if fails:
    sys.exit("contrast failures:\n" + "\n".join(fails))

def block(theme, mode):
    v = dict(t["themes"][theme][mode]); v.update(t["status"][mode])
    return "".join(f"--{k}:{val};" for k, val in v.items())

def accent(a, mode):
    av = t["accents"][a]
    return f"--accent:{av[mode]};--accentSoft:{av[mode + 'Soft']};--onAccent:{av['onLight' if mode == 'light' else 'onDark']};"

order = lambda d, k: sorted(d, key=lambda x: x != t["defaults"][k])
out = ["/* Generated by gen_tokens.py from tokens.json. Do not edit by hand. */"]
for th in order(t["themes"], "theme"):
    sel = ":root" if th == t["defaults"]["theme"] else f':root[data-palette="{th}"]'
    out.append(f"{sel}{{{block(th,'light')}}}")
    out.append(f'@media (prefers-color-scheme: dark){{{sel}:not([data-theme="light"]){{{block(th,"dark")}color-scheme:dark}}}}')
    out.append(f'{sel}[data-theme="dark"]{{{block(th,"dark")}color-scheme:dark}}')
for a in order(t["accents"], "accentColor"):
    sel = ":root" if a == t["defaults"]["accentColor"] else f':root[data-accent="{a}"]'
    out.append(f"{sel}{{{accent(a,'light')}}}")
    out.append(f'@media (prefers-color-scheme: dark){{{sel}:not([data-theme="light"]){{{accent(a,"dark")}}}}}')
    out.append(f'{sel}[data-theme="dark"]{{{accent(a,"dark")}}}')
(here / "tokens.css").write_text("\n".join(out) + "\n")
print("tokens.css written; all contrast pairs pass AA")
