#!/usr/bin/env python3
"""Writes Sources/HeronUI/Tokens/GeneratedTokens.swift from docs/designs/heron-mac-visual/tokens.json.

tokens.json is the only source of colour values (heron-mac-visual.md, Design tokens).
Run from the repo root:  python3 -I macos/HeronMac/Scripts/gen_tokens_swift.py
A test in HeronUITests checks the generated values against tokens.json again, so a stale file fails.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[3]
tokens = json.loads((root / "docs/designs/heron-mac-visual/tokens.json").read_text())
out = root / "macos/HeronMac/Sources/HeronUI/Tokens/GeneratedTokens.swift"


def hx(v: str) -> str:
    return "0x" + v.lstrip("#").upper()


roles = ["window", "sidebar", "surface", "raised", "hairline", "ink", "ink2", "ink3"]
lines = [
    "// Generated by Scripts/gen_tokens_swift.py from docs/designs/heron-mac-visual/tokens.json. Do not edit.",
    "",
    "enum GeneratedTokens {",
    "    static let neutralRoles = [" + ", ".join(f'"{r}"' for r in roles) + "]",
    "",
    "    /// theme -> mode -> the eight neutral roles, in `neutralRoles` order.",
    "    static let neutrals: [String: [String: [UInt32]]] = [",
]
for theme, modes in tokens["themes"].items():
    lines.append(f'        "{theme}": [')
    for mode in ("light", "dark"):
        vals = ", ".join(hx(modes[mode][r]) for r in roles)
        lines.append(f'            "{mode}": [{vals}],')
    lines.append("        ],")
lines += ["    ]", "", "    /// accent -> key (light, dark, lightSoft, darkSoft, onLight, onDark) -> colour.", "    static let accents: [String: [String: UInt32]] = ["]
for name, vals in tokens["accents"].items():
    body = ", ".join(f'"{k}": {hx(v)}' for k, v in vals.items())
    lines.append(f'        "{name}": [{body}],')
lines += ["    ]", "", "    /// mode -> status role -> colour.", "    static let status: [String: [String: UInt32]] = ["]
for mode in ("light", "dark"):
    body = ", ".join(f'"{k}": {hx(v)}' for k, v in tokens["status"][mode].items())
    lines.append(f'        "{mode}": [{body}],')
lines += ["    ]", "", "    static let defaults: [String: String] = ["]
for k, v in tokens["defaults"].items():
    lines.append(f'        "{k}": "{v}",')
lines += ["    ]", "}", ""]
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines))
print("wrote", out.relative_to(root))
